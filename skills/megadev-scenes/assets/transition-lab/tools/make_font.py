def build():
 out=bytearray()
 for char in range(32,128):
  rows=GLYPHS.get(chr(char),['00000']*7)
  for y in range(8):
   pixels=[2]*8
   if y<7:
    for x in range(5):
     if rows[y][x]=='1':pixels[x+1]=1
   out.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,8,2))
 return bytes(out)
def beacon():
 # Dedicated transparent 16x16 marker; HUD font tiles have opaque backgrounds.
 rows=[]
 for y in range(16):
  row=[]
  for x in range(16):
   distance=abs(x-7)+abs(y-7)
   row.append(1 if distance in (6,7) else 3 if distance<6 else 0)
  rows.append(row)
 out=bytearray()
 # VDP sprites store tile columns first, then rows.
 for tx in range(2):
  for ty in range(2):
   for y in range(8):
    line=rows[ty*8+y][tx*8:tx*8+8]
    out.extend((line[x]<<4)|line[x+1] for x in range(0,8,2))
 return bytes(out)
