#!/usr/bin/env python3
"""Compile readable UTF-8 catalogs to a validated private glyph codec."""
import argparse,json,re,struct,unicodedata
from pathlib import Path
from loc_glyphs import rows
ROOT=Path(__file__).resolve().parents[1]
NAME_CHARS='ABCDEFGHIJKLMNOPQRSTUVWXYZÀÉÑÖÜÇ0123456789'
FONT_SLOTS=192
TOKENS={'name':253,'count':254}
NEWLINE=252

def unique(pairs):
 out={}
 for key,value in pairs:
  if key in out:raise ValueError('Duplicate JSON key: '+key)
  out[key]=value
 return out

def text(value):
 if not isinstance(value,str):raise ValueError('Translation must be a string')
 value=unicodedata.normalize('NFC',value)
 if not value.strip():raise ValueError('Translation cannot be empty')
 if any((ord(c)<32 and c!='\n') or ord(c)==127 for c in value):raise ValueError('Unsupported control character')
 return value

def pieces(value):
 parts=[];pos=0
 for m in re.finditer(r'\{([^{}]*)\}',value):
  literal=value[pos:m.start()]
  if '{' in literal or '}' in literal:raise ValueError('Unbalanced placeholder')
  if m[1] not in TOKENS:raise ValueError('Unknown placeholder: '+m[1])
  parts.append(literal);parts.append(TOKENS[m[1]]);pos=m.end()
 tail=value[pos:]
 if '{' in tail or '}' in tail:raise ValueError('Unbalanced placeholder')
 parts.append(tail);return parts

def compile_data(source):
 if isinstance(source,(str,Path)):source=json.loads(Path(source).read_text(encoding='utf-8'),object_pairs_hook=unique)
 languages=source['languages'];messages=source['messages'];ids=source['ids']
 if not languages or len(languages)>8 or len(set(languages))!=len(languages) or any(not re.fullmatch('[a-z]{2,3}',l) for l in languages):raise ValueError('Unique lowercase language keys required')
 if len(set(ids))!=len(ids) or set(ids)!=set(messages) or len(ids)>255:raise ValueError('Explicit message IDs must match catalog exactly')
 if any(not re.fullmatch('[a-z][a-z0-9_]*',s) for s in ids):raise ValueError('Invalid message ID')
 normalized={};parsed={};chars=set(chr(n) for n in range(32,127))|set(NAME_CHARS)|set('LÉO')
 for mid in ids:
  values=messages[mid]
  if not isinstance(values,list) or len(values)!=len(languages):raise ValueError(mid+': every locale needs a translation')
  normalized[mid]=[text(v) for v in values];parsed[mid]=[pieces(v) for v in normalized[mid]]
  contract=sorted(p for p in parsed[mid][0] if isinstance(p,int))
  for lang,parts in zip(languages,parsed[mid]):
   if sorted(p for p in parts if isinstance(p,int))!=contract:raise ValueError(mid+'/'+lang+': placeholder mismatch')
   for p in parts:
    if isinstance(p,str):chars.update(c for c in p if c!='\n')
 glyphs=''.join(chr(n) for n in range(32,127))+''.join(sorted(chars-set(chr(n) for n in range(32,127))))
 if len(glyphs)>FONT_SLOTS:raise ValueError('Font reservation exceeded')
 for ch in glyphs:
  r=rows(ch)
  if len(r)!=8 or any(not 0<=v<256 for v in r):raise ValueError('Invalid native glyph: '+ch)
 codec={ch:i+1 for i,ch in enumerate(glyphs)}
 def encode(parts):
  out=[]
  for part in parts:
   if isinstance(part,int):out.append(part)
   else:out.extend(NEWLINE if ch=='\n' else codec[ch] for ch in part)
  return bytes(out)+b'\0'
 blob=bytearray();offsets=[];lengths=[];decoded=[]
 for language in range(len(languages)):
  for mid in ids:
   b=encode(parsed[mid][language]);offsets.append(len(blob));lengths.append(len(b)-1);blob.extend(b);decoded.append(b)
 if len(blob)>65535:raise ValueError('Catalog exceeds this example\'s 16-bit offset format')
 # Reject untranslated screen overflow with worst-case substitutions. Text boxes
 # wrap; one-line labels/footers have explicit measured widths.
 for mid in ids:
  for lang,parts in zip(languages,parsed[mid]):
   expanded=''.join('WWWWWWWW' if p==253 else '65535' if p==254 else p for p in parts)
   if len(expanded)>383:raise ValueError(mid+'/'+lang+': formatted text exceeds 383 glyphs')
   limit=34 if mid.endswith('_help') else 30 if mid!='story' else None
   if limit and ('\n' in expanded or len(expanded)>limit):raise ValueError(mid+'/'+lang+': one-line layout overflow')
 return {'languages':languages,'ids':ids,'glyphs':glyphs,'codec':codec,'blob':bytes(blob),'offsets':offsets,'lengths':lengths,'encoded':decoded,'normalized':normalized}

def generate(source=None,destination=None):
 d=compile_data(source or ROOT/'res/catalog.json');out=Path(destination or ROOT);(out/'src').mkdir(parents=True,exist_ok=True);(out/'res').mkdir(exist_ok=True)
 header='/* Generated by tools/catalog.py; edit res/catalog.json. */\n#ifndef LC_CATALOG_H\n#define LC_CATALOG_H\n'
 header+=f'#define LC_LANGUAGES {len(d["languages"])}\n#define LC_MESSAGES {len(d["ids"])}\n#define LC_GLYPHS {len(d["glyphs"])}\n#define LC_FONT_SLOTS {FONT_SLOTS}\n#define LC_NAME_COUNT {len(NAME_CHARS)}\n'
 header+='enum {'+','.join('LC_M_'+s.upper() for s in d['ids'])+'};\n'
 header+='extern unsigned char const lc_blob[],lc_name_grid[],lc_default_name[];\nextern unsigned short const lc_offsets[],lc_lengths[];\n#endif\n'
 def array(name,values,kind):return kind+' const '+name+'[]={'+','.join(str(v) for v in values)+'};\n'
 code='#include "catalog.h"\n'+array('lc_blob',d['blob'],'unsigned char')+array('lc_offsets',d['offsets'],'unsigned short')+array('lc_lengths',d['lengths'],'unsigned short')+array('lc_name_grid',[d['codec'][c] for c in NAME_CHARS],'unsigned char')+array('lc_default_name',[d['codec'][c] for c in 'LÉO']+[0],'unsigned char')
 (out/'src/catalog.h').write_text(header,encoding="utf-8",newline="\n");(out/'src/catalog.c').write_text(code,encoding="utf-8",newline="\n")
 report={'languages':d['languages'],'messages':len(d['ids']),'glyphs':len(d['glyphs']),'pattern_bytes':len(d['glyphs'])*32,'reserved_tiles':FONT_SLOTS,'reserved_bytes':FONT_SLOTS*32,'catalog_bytes':len(d['blob'])+4*len(d['offsets']),'glyph_order':d['glyphs'],'language_keys':dict(enumerate(d['languages']))}
 (out/'res/catalog-report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
 return report
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--catalog',type=Path);p.add_argument('--output',type=Path);a=p.parse_args()
 try:print(json.dumps(generate(a.catalog,a.output),ensure_ascii=False))
 except (ValueError,KeyError,TypeError) as e:p.exit(2,str(e)+'\n')
